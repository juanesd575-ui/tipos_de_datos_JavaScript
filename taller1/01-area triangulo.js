//formula = (base * altura) / 2
//AT = area de triangulo
// B= base
// H= altura

//cambiar estos valores por otros para calcular el area de otro triangulo

const base = 10; //base del triangulo (numero)
const altura = 4; //altura del triangulo (numero)

//aplicamos la formula para calcular el area del triangulo
const areaTriangulo = (base * altura) / 2; //area del triangulo (numero)

//mostramos el resultado en la consola
console.log("el area del triangulo es: "+ areaTriangulo); //muestra el area del ttriangulo en la consola
console.log("la base del triangulo es: "+ base); //muestra la base del triangulo en la consola
console.log("la altura del triangulo es: "+ altura); // muestra la altura del triangulo en la consola